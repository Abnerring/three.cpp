// A real zlib stream: a standard compressor packed the text below with the dynamic Huffman kind,
// and the header and checksum were added by hand. The hand built streams in the other tests never
// reach that kind, so this one is what exercises those layers.
std::string realText() {
    std::string text;
    for (int i = 0; i < 40; ++i) {
        text += "line " + std::to_string(i) + " of a contrived file, with varied words: ";
        text += "alpha beta gamma delta epsilon zeta eta theta iota kappa. ";
    }
    return text;
}

