"""Generate Unicode 17.0 NFC tables. Usage: python ... <external-cache-dir>.

The Unicode data is covered by src/core/Unicode-LICENSE.txt. The cache must stay
outside the source tree. Python's own (possibly older) Unicode database is unused.
"""
from pathlib import Path
import hashlib
import sys
import urllib.request

VERSION = '17.0.0'
HASHES = {
    'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
    'CompositionExclusions.txt': '2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f',
    'license.txt': 'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96',
}
root = Path(__file__).resolve().parents[1]
cache = Path(sys.argv[1]).resolve()
if cache.is_relative_to(root):
    raise SystemExit('Use an external cache directory')
cache.mkdir(parents=True, exist_ok=True)

def fetch(name, url=None):
    dest = cache / name
    if not dest.exists():
        with urllib.request.urlopen(url or f'https://www.unicode.org/Public/{VERSION}/ucd/{name}') as response:
            dest.write_bytes(response.read())
    data = dest.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != HASHES[name]:
        raise SystemExit(f'{name}: SHA256 mismatch: {digest}')
    print(name, digest)
    return data.decode('utf-8')

data = fetch('UnicodeData.txt')
excluded = {int(line.split('#')[0].strip(), 16) for line in fetch('CompositionExclusions.txt').splitlines()
            if line.split('#')[0].strip()}
decompositions, classes = {}, {}
for line in data.splitlines():
    fields = line.split(';')
    code, combining, decomposition = int(fields[0], 16), int(fields[3]), fields[5]
    if combining:
        classes[code] = combining
    if decomposition and not decomposition.startswith('<'):
        decompositions[code] = [int(part, 16) for part in decomposition.split()]
compositions = sorted((parts[0], parts[1], code) for code, parts in decompositions.items()
                      if len(parts) == 2 and code not in excluded and not classes.get(parts[0], 0))
out = ['// Generated by utils/generate-unicode-normalization.py; Unicode 17.0.0.',
       '// Unicode data license: Unicode-LICENSE.txt. Do not edit.',
       '// Source: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt',
       '// Source: https://www.unicode.org/Public/17.0.0/ucd/CompositionExclusions.txt',
       '#pragma once', '#include <cstdint>', 'namespace Unicode_detail {',
       'struct Decomposition { std::uint32_t code, first, second; };',
       'inline constexpr Decomposition decompositions[] = {']
out += [f'    {{0x{code:x},0x{parts[0]:x},0x{parts[1] if len(parts)>1 else 0:x}}},'
        for code, parts in sorted(decompositions.items())]
out += ['};', 'struct CombiningClass { std::uint32_t code; unsigned value; };',
        'inline constexpr CombiningClass combiningClasses[] = {']
out += [f'    {{0x{code:x},{value}}},' for code, value in sorted(classes.items())]
out += ['};', 'struct Composition { std::uint32_t first, second, result; };',
        'inline constexpr Composition compositions[] = {']
out += [f'    {{0x{first:x},0x{second:x},0x{result:x}}},' for first, second, result in compositions]
out += ['};', '}']
(root / 'src/core/UnicodeNormalizationData.h').write_text('\n'.join(out)+'\n', encoding='utf-8',newline='\n')
(root / 'src/core/Unicode-LICENSE.txt').write_bytes(fetch('license.txt','https://www.unicode.org/license.txt').encode('utf-8'))
print(len(decompositions), 'decompositions;', len(classes), 'combining classes;', len(compositions), 'compositions')
