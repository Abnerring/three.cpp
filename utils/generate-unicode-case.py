"""Generate the Unicode 17 default uppercase mapping, without Python Unicode data.

Usage: python utils/generate-unicode-case.py <external-cache-dir> [--check]
Unicode data license: src/core/Unicode-LICENSE.txt (already shared by NFC data).
"""
from pathlib import Path
import hashlib
import sys
import urllib.request
VERSION = '17.0.0'
HASHES = {
    'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
    'SpecialCasing.txt': 'efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588',
}
if len(sys.argv) not in (2,3) or len(sys.argv)==3 and sys.argv[2]!='--check':
    raise SystemExit(__doc__)
root=Path(__file__).resolve().parents[1]
cache=Path(sys.argv[1]).resolve()
if cache.is_relative_to(root):raise SystemExit('Use an external cache directory')
cache.mkdir(parents=True,exist_ok=True)
def fetch(name):
    p=cache/name
    if not p.exists():
        with urllib.request.urlopen(f'https://www.unicode.org/Public/{VERSION}/ucd/{name}') as response:
            p.write_bytes(response.read())
    raw=p.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=HASHES[name]:raise SystemExit(f'{name}: SHA256 mismatch')
    return raw.decode('utf-8')
mappings={}
for line in fetch('UnicodeData.txt').splitlines():
    fields=line.split(';')
    if fields[12]:mappings[int(fields[0],16)]=[int(fields[12],16)]
for raw in fetch('SpecialCasing.txt').splitlines():
    line=raw.split('#',1)[0].strip()
    if not line:continue
    fields=[f.strip() for f in line.split(';')]
    point=int(fields[0],16);upper=[int(p,16) for p in fields[3].split()]
    condition=fields[4]
    if not condition:mappings[point]=upper
    elif condition=='Final_Sigma':
        # Unicode 17's only non-locale context affects lowercase, not uppercase.
        assert upper==mappings.get(point,[point])
    else:
        # These rules belong to locale-sensitive conversion, not toUpperCase.
        assert condition.split()[0] in ('tr','az','lt'),condition
mappings={p:v for p,v in mappings.items() if v!=[p]}
assert all(0<len(v)<=3 for v in mappings.values())
lines=['// Generated by utils/generate-unicode-case.py; Unicode 17.0.0.',
       '// Unicode data license: Unicode-LICENSE.txt. Do not edit.',
       '// Source: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt',
       '// Source: https://www.unicode.org/Public/17.0.0/ucd/SpecialCasing.txt',
       '#pragma once','#include <cstdint>','namespace UnicodeCase_detail {',
       'struct UpperMapping { std::uint32_t point, result[3]; unsigned count; };',
       'inline constexpr UpperMapping upperMappings[] = {']
for point,values in sorted(mappings.items()):
    padded=values+[0]*(3-len(values))
    lines.append('    {0x%x,{%s},%d},'%(point,','.join('0x%x'%v for v in padded),len(values)))
lines+=['};','}']
text='\n'.join(lines)+'\n';target=root/'src/core/UnicodeCaseData.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text(encoding='utf-8')!=text:raise SystemExit('UnicodeCaseData.h is stale')
else:target.write_text(text,encoding='utf-8',newline='\n')
print(len(mappings),'default uppercase mappings; Unicode',VERSION)
