JSValue nativeBokehShader() {
    static thread_local JSWeakValue cache;
    if (const auto existing = cache.lock(); existing && existing->isObject()) return *existing;
    static thread_local bool initializing = false;
    JSModuleInitializationScope initialization(initializing, "BokehShader");
    JSValue result = object({
        {"BokehShader", object({
            {"name", "BokehShader"},
            {"defines", object({
                {"DEPTH_PACKING", 1},
                {"PERSPECTIVE_CAMERA", 1}
            })},
            {"uniforms", object({
                {"tColor", object({
                    {"value", nullptr}
                })},
                {"tDepth", object({
                    {"value", nullptr}
                })},
                {"focus", object({
                    {"value", 1}
                })},
                {"aspect", object({
                    {"value", 1}
                })},
                {"aperture", object({
                    {"value", 0.025}
                })},
                {"maxblur", object({
                    {"value", 0.01}
                })},
                {"nearClip", object({
                    {"value", 1}
                })},
                {"farClip", object({
                    {"value", 1000}
                })}
            })},
            {"vertexShader", std::string(BokehShader_BokehShader_vertexShader)},
            {"fragmentShader", std::string(BokehShader_BokehShader_fragmentShader)}
        })}
    });
    result.retainForHeapLifetime();cache=JSWeakValue(result);return result;
}
